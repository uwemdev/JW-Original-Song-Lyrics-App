-- Creates tables for tracking mobile search queries, zero-result terms, and song engagement events

-- 1. Search logs table (tracks search terms and zero-result queries)
CREATE TABLE IF NOT EXISTS public.app_search_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  query TEXT NOT NULL,
  results_count INTEGER NOT NULL DEFAULT 0,
  device_id TEXT,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- Indexes for performant search insights, zero-result aggregation, and date range filtering
CREATE INDEX IF NOT EXISTS idx_app_search_logs_created_at ON public.app_search_logs(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_app_search_logs_query ON public.app_search_logs(query);
CREATE INDEX IF NOT EXISTS idx_app_search_logs_results_count ON public.app_search_logs(results_count);
CREATE INDEX IF NOT EXISTS idx_app_search_logs_device_id ON public.app_search_logs(device_id);

-- Enable RLS
ALTER TABLE public.app_search_logs ENABLE ROW LEVEL SECURITY;

-- Allow anonymous app users to log searches
CREATE POLICY "Anyone can insert search logs"
  ON public.app_search_logs FOR INSERT
  WITH CHECK (true);

-- Allow authenticated admin users to read and manage search logs
CREATE POLICY "Admins can view search logs"
  ON public.app_search_logs FOR SELECT
  USING (auth.role() = 'authenticated');

CREATE POLICY "Admins can delete search logs"
  ON public.app_search_logs FOR DELETE
  USING (auth.role() = 'authenticated');


-- 2. Song engagement events table (tracks plays, views, downloads, status shares, favorites)
CREATE TABLE IF NOT EXISTS public.app_song_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  song_id UUID NOT NULL REFERENCES public.songs(id) ON DELETE CASCADE,
  event_type TEXT NOT NULL,
  device_id TEXT,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- Indexes for fast aggregation by song, event type, and date range
CREATE INDEX IF NOT EXISTS idx_app_song_events_created_at ON public.app_song_events(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_app_song_events_song_id ON public.app_song_events(song_id);
CREATE INDEX IF NOT EXISTS idx_app_song_events_event_type ON public.app_song_events(event_type);
CREATE INDEX IF NOT EXISTS idx_app_song_events_device_id ON public.app_song_events(device_id);

-- Enable RLS
ALTER TABLE public.app_song_events ENABLE ROW LEVEL SECURITY;

-- Allow anonymous app users to track song interactions
CREATE POLICY "Anyone can insert song events"
  ON public.app_song_events FOR INSERT
  WITH CHECK (true);

-- Allow authenticated admin users to read and analyze song events
CREATE POLICY "Admins can view song events"
  ON public.app_song_events FOR SELECT
  USING (auth.role() = 'authenticated');

CREATE POLICY "Admins can delete song events"
  ON public.app_song_events FOR DELETE
  USING (auth.role() = 'authenticated');
