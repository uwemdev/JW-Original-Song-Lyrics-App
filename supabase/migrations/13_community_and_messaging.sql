-- Community Hub: Anonymous randomized IDs (e.g. U71234), 2go stars,
-- IP/Device multi-day ban system, group chat lounge, and mutual direct message requests.

-- Clean out any previous partial community tables to avoid column mismatch
DROP TABLE IF EXISTS public.community_reports CASCADE;
DROP TABLE IF EXISTS public.community_direct_messages CASCADE;
DROP TABLE IF EXISTS public.community_direct_threads CASCADE;
DROP TABLE IF EXISTS public.community_group_messages CASCADE;
DROP TABLE IF EXISTS public.community_bans CASCADE;
DROP TABLE IF EXISTS public.community_profiles CASCADE;

-- 1. Community User Profiles
CREATE TABLE public.community_profiles (
  device_id TEXT PRIMARY KEY,
  handle TEXT NOT NULL UNIQUE,          -- e.g. U71234
  avatar_id INTEGER NOT NULL DEFAULT 1,  -- 1 through 12
  star_level INTEGER NOT NULL DEFAULT 1, -- 1 through 5
  country_name TEXT,                    -- e.g. 'United States'
  country_code TEXT,                    -- e.g. 'US'
  ip_address TEXT,
  is_banned BOOLEAN NOT NULL DEFAULT false,
  banned_until TIMESTAMPTZ,
  ban_reason TEXT,
  last_active_at TIMESTAMPTZ DEFAULT now(),
  terms_accepted_at TIMESTAMPTZ DEFAULT now(),
  created_at TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX idx_community_profiles_handle ON public.community_profiles(handle);
CREATE INDEX idx_community_profiles_ip ON public.community_profiles(ip_address);
CREATE INDEX idx_community_profiles_last_active ON public.community_profiles(last_active_at DESC);

ALTER TABLE public.community_profiles ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Anyone can view active profiles"
  ON public.community_profiles FOR SELECT
  USING (true);

CREATE POLICY "Users can create or update own profile"
  ON public.community_profiles FOR ALL
  USING (true)
  WITH CHECK (true);


-- 2. Community IP and Device Bans Table
CREATE TABLE public.community_bans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id TEXT,
  ip_address TEXT,
  banned_until TIMESTAMPTZ, -- null = permanent
  reason TEXT,
  banned_by TEXT DEFAULT 'admin',
  created_at TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX idx_community_bans_device ON public.community_bans(device_id);
CREATE INDEX idx_community_bans_ip ON public.community_bans(ip_address);
CREATE INDEX idx_community_bans_until ON public.community_bans(banned_until);

ALTER TABLE public.community_bans ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Anyone can read bans to check status"
  ON public.community_bans FOR SELECT
  USING (true);

CREATE POLICY "Admins can manage bans"
  ON public.community_bans FOR ALL
  USING (auth.role() = 'authenticated')
  WITH CHECK (auth.role() = 'authenticated');


-- 3. Group Lounge Messages (Main Community Chat)
CREATE TABLE public.community_group_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_device_id TEXT NOT NULL REFERENCES public.community_profiles(device_id) ON DELETE CASCADE,
  sender_handle TEXT NOT NULL,
  sender_star_level INTEGER NOT NULL DEFAULT 1,
  sender_avatar_id INTEGER NOT NULL DEFAULT 1,
  sender_country_code TEXT,
  message TEXT NOT NULL,
  is_flagged BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX idx_community_group_messages_created ON public.community_group_messages(created_at DESC);
CREATE INDEX idx_community_group_messages_sender ON public.community_group_messages(sender_device_id);

ALTER TABLE public.community_group_messages ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Anyone can read group messages"
  ON public.community_group_messages FOR SELECT
  USING (true);

CREATE POLICY "Anyone can post group messages"
  ON public.community_group_messages FOR INSERT
  WITH CHECK (true);

CREATE POLICY "Admins can delete group messages"
  ON public.community_group_messages FOR DELETE
  USING (auth.role() = 'authenticated');


-- 4. Direct Message Threads (User A to User B with Accept/Decline flow)
CREATE TABLE public.community_direct_threads (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  requester_device_id TEXT NOT NULL REFERENCES public.community_profiles(device_id) ON DELETE CASCADE,
  recipient_device_id TEXT NOT NULL REFERENCES public.community_profiles(device_id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'pending', -- 'pending', 'accepted', 'declined', 'blocked'
  last_message_at TIMESTAMPTZ DEFAULT now(),
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now(),
  CONSTRAINT uq_community_direct_threads UNIQUE (requester_device_id, recipient_device_id)
);

CREATE INDEX idx_direct_threads_requester ON public.community_direct_threads(requester_device_id);
CREATE INDEX idx_direct_threads_recipient ON public.community_direct_threads(recipient_device_id);
CREATE INDEX idx_direct_threads_status ON public.community_direct_threads(status);

ALTER TABLE public.community_direct_threads ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can access their own threads"
  ON public.community_direct_threads FOR ALL
  USING (true)
  WITH CHECK (true);


-- 5. Direct Messages (Texts between two users)
CREATE TABLE public.community_direct_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_id UUID NOT NULL REFERENCES public.community_direct_threads(id) ON DELETE CASCADE,
  sender_device_id TEXT NOT NULL REFERENCES public.community_profiles(device_id) ON DELETE CASCADE,
  message TEXT NOT NULL,
  is_read BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX idx_direct_messages_thread ON public.community_direct_messages(thread_id, created_at ASC);
CREATE INDEX idx_direct_messages_sender ON public.community_direct_messages(sender_device_id);

ALTER TABLE public.community_direct_messages ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can access messages in their threads"
  ON public.community_direct_messages FOR ALL
  USING (true)
  WITH CHECK (true);


-- 6. Community Reports (Flagged messages sent to admin panel)
CREATE TABLE public.community_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reporter_device_id TEXT NOT NULL,
  reported_device_id TEXT NOT NULL,
  reported_handle TEXT NOT NULL,
  message_id BIGINT,
  message_text TEXT NOT NULL,
  chat_type TEXT NOT NULL DEFAULT 'group', -- 'group' or 'direct'
  reason TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending', -- 'pending', 'resolved', 'dismissed'
  created_at TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX idx_community_reports_status ON public.community_reports(status);
CREATE INDEX idx_community_reports_created ON public.community_reports(created_at DESC);

ALTER TABLE public.community_reports ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Anyone can submit a report"
  ON public.community_reports FOR INSERT
  WITH CHECK (true);

CREATE POLICY "Admins can view and manage reports"
  ON public.community_reports FOR ALL
  USING (auth.role() = 'authenticated')
  WITH CHECK (auth.role() = 'authenticated');


